# --- ПРЕЦИЗЕН ЛИНГВИСТИЧЕН ДВИГАТЕЛ ЗА БЪЛГАРСКИ ПАЗАР ---
def пречисти_български_текст(текст: str) -> str:
    речник_на_термините = {
        "клиентски опит": "потребителско изживяване",
        "лайк": "харесване",
        "шервам": "споделям",
        "бууствам": "промотирам",
        "хук": "улавяща кука",
        "криейтър": "създател на съдържание"
    }
    for грешен, правилен in речник_на_термините.items():
        текст = текст.replace(грешен, правилен)
    return текст.strip()

